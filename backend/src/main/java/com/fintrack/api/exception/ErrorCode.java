package com.fintrack.api.exception;

public enum ErrorCode {
    VALIDATION_ERROR,
    BAD_REQUEST,
    UNAUTHORIZED,
    FORBIDDEN,
    NOT_FOUND,
    METHOD_NOT_ALLOWED,
    UNSUPPORTED_MEDIA_TYPE,
    REQUEST_ERROR,
    INTERNAL_ERROR,
    FINANCE_AMOUNT_OVERFLOW,
    WALLET_NAME_CONFLICT,
    WALLET_ARCHIVED,
    WALLET_INSUFFICIENT_FUNDS,
    CATEGORY_NAME_CONFLICT,
    CATEGORY_TYPE_IN_USE,
    CATEGORY_ARCHIVED,
    BUDGET_PERIOD_CONFLICT,
    BUDGET_ARCHIVED,
    BUDGET_MONTH_MISSING,
    BUDGET_MONTH_CURRENT,
    BUDGET_EXCEEDS_AVAILABLE_BALANCE,
    TRANSACTION_TYPE_UNSUPPORTED,
    TRANSACTION_REQUEST_CONFLICT,
    TRANSACTION_VOIDED,
    AUTH_INVALID_CREDENTIALS,
    AUTH_USERNAME_NOT_EXIST,
    AUTH_ACCESS_TOKEN_INVALID,
    AUTH_REFRESH_TOKEN_INVALID,
    AUTH_EMAIL_NOT_VERIFIED,
    AUTH_USER_LOCKED,
    AUTH_USER_DISABLED,
    AUTH_EMAIL_ALREADY_EXISTS,
    AUTH_USERNAME_ALREADY_EXISTS,
    AUTH_OTP_INVALID,
    AUTH_OTP_EXPIRED,
    AUTH_OTP_ATTEMPTS_EXCEEDED,
    AUTH_RATE_LIMIT_UNAVAILABLE,
    AUTH_RATE_LIMITED;

    public static ErrorCode forStatus(int status) {
        return switch (status) {
            case 400 -> BAD_REQUEST;
            case 401 -> UNAUTHORIZED;
            case 403 -> FORBIDDEN;
            case 404 -> NOT_FOUND;
            case 405 -> METHOD_NOT_ALLOWED;
            case 415 -> UNSUPPORTED_MEDIA_TYPE;
            default -> status >= 500 ? INTERNAL_ERROR : REQUEST_ERROR;
        };
    }
}
